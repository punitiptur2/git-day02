#!/usr/bin/env python3

# Python3 program: Calculate factorial

num = int(input("Enter a number: "))

factorial = 1

for i in range(1, num + 1):
    factorial *= i

print(f"Factorial of {num} is {factorial}")#!/usr/bin/env python3

